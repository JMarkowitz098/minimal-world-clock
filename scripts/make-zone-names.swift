#!/usr/bin/env swift
// Writes Packages/WorldClockKit/Sources/WorldClockCore/ZoneNames.swift: for every zone this Mac
// knows, its country (ISO 3166 code, from macOS's copy of the tz database's zone.tab, public
// domain) and the English names search matches: the country's name and the zone's names
// ("Pacific Time", "Pacific Standard Time"), from Foundation. Precomputed because asking
// Foundation for the zone names takes ~30 ms per process. Run from the repo root after a
// macOS update changes the zone list, or to change the language:
//     swift scripts/make-zone-names.swift
import Foundation

let english = Locale(identifier: "en_US")
let known = TimeZone.knownTimeZoneIdentifiers.sorted()
let tab = try String(contentsOfFile: "/usr/share/zoneinfo/zone.tab", encoding: .utf8)

var countries: [String: String] = [:]
for line in tab.split(separator: "\n") where !line.hasPrefix("#") {
    let fields = line.split(separator: "\t")
    countries[String(fields[2])] = String(fields[0])
}

// zone.tab uses today's names; the system also lists older ones (and sometimes only those).
let oldNames: [String: String] = [
    "America/Godthab": "GL", "America/Montreal": "CA", "America/Nipigon": "CA",
    "America/Pangnirtung": "CA", "America/Rainy_River": "CA", "America/Santa_Isabel": "MX",
    "America/Shiprock": "US", "America/Thunder_Bay": "CA", "America/Yellowknife": "CA",
    "Antarctica/South_Pole": "AQ", "Asia/Calcutta": "IN", "Asia/Choibalsan": "MN",
    "Asia/Chongqing": "CN", "Asia/Harbin": "CN", "Asia/Kashgar": "CN", "Asia/Katmandu": "NP",
    "Asia/Rangoon": "MM", "Australia/Currie": "AU", "Europe/Kiev": "UA", "Europe/Uzhgorod": "UA",
    "Europe/Zaporozhye": "UA", "Pacific/Enderbury": "KI", "Pacific/Johnston": "UM",
    "Pacific/Ponape": "FM", "Pacific/Truk": "FM",
]
countries.merge(oldNames) { current, _ in current }

var lines: [String] = []
for identifier in known {
    let timeZone = TimeZone(identifier: identifier)!
    let code = countries[identifier] ?? ""
    var names: [String] = []
    if let country = english.localizedString(forRegionCode: code), !code.isEmpty { names.append(country) }
    for style in [NSTimeZone.NameStyle.generic, .standard, .daylightSaving] {
        if let name = timeZone.localizedName(for: style, locale: english), !names.contains(name) { names.append(name) }
    }
    lines.append([identifier, code, names.joined(separator: "|")].joined(separator: "\t"))
}
let noCountry = known.filter { countries[$0] == nil }

let source = """
// Generated by scripts/make-zone-names.swift (countries from /usr/share/zoneinfo/zone.tab, tz
// database, public domain; names from Foundation, in English). Don't edit by hand; rerun it.

/// Each zone's country and the names search matches besides its city: the country's name and
/// the zone's names ("Japan", "Japan Standard Time"). Zones with no country: \(noCountry.joined(separator: ", ")).
enum ZoneNames {
    /// The zone's country as an ISO 3166 code ("Asia/Tokyo" → "JP"), or nil.
    static func countryCode(for identifier: String) -> String? {
        entries[identifier]?.code
    }

    /// The country's name and the zone's names, in English.
    static func names(for identifier: String) -> [String] {
        entries[identifier]?.names ?? []
    }

    private static let entries: [String: (code: String?, names: [String])] = {
        var entries: [String: (code: String?, names: [String])] = [:]
        for line in table.split(separator: "\\n") {
            let fields = line.split(separator: "\\t", omittingEmptySubsequences: false)
            entries[String(fields[0])] = (fields[1].isEmpty ? nil : String(fields[1]), fields[2].split(separator: "|").map(String.init))
        }
        return entries
    }()

    private static let table = \"\"\"
\(lines.joined(separator: "\n"))
\"\"\"
}

"""
try source.write(toFile: "Packages/WorldClockKit/Sources/WorldClockCore/ZoneNames.swift", atomically: true, encoding: .utf8)
print("\(lines.count) zones; no country: \(noCountry)")
